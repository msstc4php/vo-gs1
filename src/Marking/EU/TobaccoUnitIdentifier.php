<?php

declare(strict_types=1);

namespace MSSTC4PHP\ValueObject\Gs1\Marking\EU;

use DateTimeImmutable;
use DateTimeZone;
use LogicException;
use MSSTC4PHP\ValueObject\Gs1\Exception\InvalidMarkingCodeException;
use MSSTC4PHP\ValueObject\Gs1\Internal\Gs1Dates;
use MSSTC4PHP\ValueObject\Support\AbstractStringValueObject;
use Override;

/**
 * The unit level UI of EU tobacco traceability: at most 50 alphanumeric characters, the ID issuer identification code
 * first and the time stamp of manufacture `YYMMDDhh` (UTC) last. The serial number and product code between them are
 * the ID issuer's own, possibly encrypted or compressed, so they are format only.
 *
 * A data carrier may hold the UI without its time stamp, printed separately (Article 21(4)): that content is
 * {@see TobaccoUnitIdentifierWithoutTimeStamp}; trailing digits are never guessed to be a time stamp.
 *
 * The century is 2000 (a package decision: the regulation dates from 2018 and the time stamp has two year digits).
 * Each of the three issuer elements takes at least one character, so the minimum length is 11.
 *
 * @see https://eur-lex.europa.eu/eli/reg_impl/2018/574/oj Implementing Regulation (EU) 2018/574, OJ L 96, 16.4.2018, Articles 8 and 2 (time stamp "recorded in UTC")
 * @see https://github.com/msstc4php/vo-gs1/blob/main/docs/sources/GS1.md "EU: falsified medicines and tobacco"
 */
final class TobaccoUnitIdentifier extends AbstractStringValueObject
{
    /** Maximum characters of the stored value, frozen for 1.x. */
    public const int MAX_LENGTH = 50;

    private const string PATTERN = '/^([0-9A-Za-z]{3,42})([0-9]{2})([0-9]{2})([0-9]{2})([0-9]{2})$/D';

    private const int MIN_LENGTH = 11;

    private const int LAST_HOUR = 23;

    /**
     * The code generated by the ID issuer (Article 8(2)), before the time stamp.
     *
     * @return non-empty-string
     */
    public function issuerPart(): string
    {
        return $this->parts()[1];
    }

    /**
     * @return non-empty-string `YYMMDDhh`
     */
    public function timeStamp(): string
    {
        $parts = $this->parts();

        return $parts[2] . $parts[3] . $parts[4] . $parts[5];
    }

    public function withoutTimeStamp(): TobaccoUnitIdentifierWithoutTimeStamp
    {
        return new TobaccoUnitIdentifierWithoutTimeStamp($this->issuerPart());
    }

    /**
     * The hour of manufacture, UTC.
     */
    public function manufacturedAt(): DateTimeImmutable
    {
        $parts = $this->parts();

        return new DateTimeImmutable(\sprintf('20%s-%s-%sT%s:00:00', $parts[2], $parts[3], $parts[4], $parts[5]), new DateTimeZone('UTC'));
    }

    #[Override]
    protected function parse(string $value): string
    {
        $length = \strlen($value);
        if ($length < self::MIN_LENGTH || $length > self::MAX_LENGTH || \preg_match('/^[0-9A-Za-z]+$/D', $value) !== 1) {
            throw new InvalidMarkingCodeException(\sprintf('Tobacco unit level UI must have %d to %d alphanumeric characters.', self::MIN_LENGTH, self::MAX_LENGTH));
        }

        if (\preg_match(self::PATTERN, $value, $match) !== 1
            || !Gs1Dates::isDate('20' . $match[2] . $match[3] . $match[4], false)
            || (int) $match[5] > self::LAST_HOUR) {
            throw new InvalidMarkingCodeException('Tobacco unit level UI must end with the time stamp YYMMDDhh.');
        }

        return $value;
    }

    /**
     * @return array{string, non-empty-string, numeric-string, numeric-string, numeric-string, numeric-string}
     */
    private function parts(): array
    {
        if (\preg_match(self::PATTERN, $this->value, $match) !== 1) {
            throw new LogicException('Tobacco unit level UI lost its time stamp.');
        }

        return $match;
    }
}
